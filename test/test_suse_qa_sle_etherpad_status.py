"""Tests for suse-qa-sle-etherpad-status: argument handling, the shell call and the markdown rewrite."""

import pytest

REPORT = """\
# Domains
## Domain: SLE-16.0-Installer
Status: RED

## Domain: SLE-16.0-Migration
Status: AMBER
"""


@pytest.fixture
def sut(load_script):
    return load_script("suse-qa-sle-etherpad-status")


@pytest.mark.parametrize(("verbose_flags", "expected"), [([], 40), (["-v"], 30), (["-v", "-v", "-v"], 10)])
def test_verbose_sets_the_log_level(sut, mocker, verbose_flags, expected):
    mocker.patch.object(sut.sys, "argv", ["suse-qa-sle-etherpad-status", *verbose_flags])
    mocker.patch.object(sut.log, "setLevel")

    sut.parse_args()

    sut.log.setLevel.assert_called_once_with(expected)


def test_parse_args_defaults(sut, mocker):
    mocker.patch.object(sut.sys, "argv", ["suse-qa-sle-etherpad-status"])

    args = sut.parse_args()

    assert args.etherpad_url == "https://etherpad.nue.suse.com/p/QA_SLE_status/"
    assert args.report_md == "~/Export/qa_sle_etherpad_status.md"
    assert args.dry_run is False


def test_call_runs_the_command_through_the_shell(sut, fake_subprocess):
    fake_subprocess.on(["curl"], returncode=3)

    assert sut.call("curl -s https://example.org") == 3
    assert fake_subprocess.commands(["curl"]) == [["curl", "-s", "https://example.org"]]


def test_call_prefixes_the_simulation_in_dry_run_mode(sut, fake_subprocess):
    fake_subprocess.on(["echo", "Simulating:"])

    sut.call("curl -s https://example.org", dry_run=True)

    assert fake_subprocess.commands(["echo", "Simulating:"]) == [
        ["echo", "Simulating:", "curl", "-s", "https://example.org"]
    ]


def test_main_rewrites_the_status_words_and_renders_html(sut, mocker, tmp_path):
    report = tmp_path / "report.md"
    report.write_text(REPORT)
    call = mocker.patch.object(sut, "call")
    mocker.patch.object(sut.sys, "argv", ["suse-qa-sle-etherpad-status", "--report-md", str(report)])

    sut.main()

    rewritten = report.read_text()
    assert '<span style="color: red;">Red</span>' in rewritten
    assert '<span style="color: #FFBF00;">Amber</span>' in rewritten
    assert "**Status: <span" in rewritten
    assert "This report was automatically generated by the script" in rewritten
    assert call.call_args_list[-1].args[0].startswith(f"markdown {report}")


def test_main_simulates_the_two_shell_calls_in_dry_run_mode(sut, mocker, tmp_path):
    report = tmp_path / "report.md"
    report.write_text(REPORT)
    call = mocker.patch.object(sut, "call")
    mocker.patch.object(sut.sys, "argv", ["suse-qa-sle-etherpad-status", "--report-md", str(report), "--dry-run"])

    sut.main()

    assert [entry.kwargs["dry_run"] for entry in call.call_args_list] == [True, True]


def test_main_keeps_a_report_without_status_words_unchanged(sut, mocker, tmp_path):
    report = tmp_path / "report.md"
    report.write_text("# Domains\n")
    mocker.patch.object(sut, "call")
    mocker.patch.object(sut.sys, "argv", ["suse-qa-sle-etherpad-status", "--report-md", str(report)])

    sut.main()

    assert report.read_text().startswith("# Domains\n")
    assert "**Status:" not in report.read_text()
